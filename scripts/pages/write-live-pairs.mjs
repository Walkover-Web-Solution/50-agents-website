// The pair pages that exist (Search S26, deploy plan decision 1): only the indexable pairs (tier core or test), each in its
// one canonical order. Written to src/content/integrations/live-pairs.json, which three places read without the catalog:
// - the pair route's generateStaticParams (every other pair is a 404, dynamicParams = false);
// - src/middleware.ts (the reversed order of a live pair, or a mixed-case slug, 308s to the canonical page);
// - src/content/integrations/paths.ts (LIVE, so MaybeLink and the app pages link only to pairs that exist).
// Run it (pnpm pages:live-pairs, Node 22.18 or later for type stripping) whenever the tiers' inputs change: the catalog
// snapshot, index-gate.json, test-cohort.json or the pair lines. The tiers come from src/site/integrations/data.ts, so the
// rule lives in one place; the pair route checks this file against the tiers and fails the build when it is stale.
import fs from 'node:fs';
import path from 'node:path';
import { register } from 'node:module';

register('../lib/ts-hooks.mjs', import.meta.url);
const { pairs, pairTier } = await import('../../src/site/integrations/data.ts');

const live = pairs().list.filter(p => pairTier(p) !== 'none').map(p => `${p.a}/${p.b}`).sort();
const out = path.join(process.cwd(), 'src/content/integrations/live-pairs.json');
const body = JSON.stringify({ note: 'Generated by scripts/pages/write-live-pairs.mjs in prebuild. Do not edit.', pairs: live }, null, 1) + '\n';
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
console.log(`live pairs: ${live.length} (src/content/integrations/live-pairs.json)`);
