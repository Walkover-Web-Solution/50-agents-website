export type CatalogApp = keyof typeof CATALOG;
/** An app's catalog icon. */
export const iconOf = (app: CatalogApp) => CATALOG[app].icon;
/** A trigger or action's exact catalog name; fails the build if the catalog read today does not list it. */
export function catalogName(app: CatalogApp, name: string): string {
  const a = CATALOG[app] as { triggers: readonly string[]; actions: readonly string[] };
  if (!a.triggers.includes(name) && !a.actions.includes(name)) throw new Error(`${app} has no "${name}" in the catalog read ${CATALOG_READ}`);
  return name;
}
/** Chips for an app's row in "What it uses": every name checked against the catalog. */
export const chips = (app: CatalogApp, names: string[]) => names.map(n => catalogName(app, n));
